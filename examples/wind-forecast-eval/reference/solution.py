"""Independent reference solution for the `compare-forecast-models` task.

Hand-written from the data description and the papers. It is NOT generated by
TerraKernel and is used only to produce the expected answer for grading. It also
computes the values that common mistakes would produce, so the grader can report
which pitfall an agent fell into.

Run:  uv run python examples/wind-forecast-eval/reference/solution.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
MATERIALS = HERE.parent / "materials"
OUT = HERE.parent / "expected" / "compare-forecast-models.json"
CHANGE = pd.Timestamp("2023-07-01T00:00:00Z")  # capacity expansion date stated in data_description.md


def load() -> tuple[pd.Series, pd.Series, pd.Series]:
    m = pd.read_csv(MATERIALS / "measured_power.csv", parse_dates=["timestamp"]).set_index("timestamp")["power_mw"]
    a = pd.read_csv(MATERIALS / "forecast_model_a.csv", parse_dates=["timestamp"]).set_index("timestamp")["forecast_mw"]
    b = pd.read_csv(MATERIALS / "forecast_model_b.csv", parse_dates=["time"]).set_index("time")["p_forecast"]
    return m, a, b


def capacity(index: pd.DatetimeIndex, reference: str = "start") -> np.ndarray:
    t = index - pd.Timedelta(hours=1) if reference == "start" else index
    return np.where(t >= CHANGE, 120.0, 100.0)


def metrics(f: pd.Series, m: pd.Series, cap: np.ndarray) -> dict[str, float]:
    e = (f - m).to_numpy()
    return {
        "mae_mw": float(np.mean(np.abs(e))),
        "rmse_mw": float(np.sqrt(np.mean(e**2))),
        "nrmse_cap_pct": float(100 * np.sqrt(np.mean((e / cap) ** 2))),
        "nrmse_const100_pct": float(100 * np.sqrt(np.mean(e**2)) / 100.0),
        "nrmse_mean_pct": float(100 * np.sqrt(np.mean(e**2)) / m.mean()),
    }


def solve(shift_a: bool = True, b_to_mw: bool = True, common: bool = True, fill_zero: bool = False,
          cap_reference: str = "start") -> dict[str, dict[str, float] | int]:
    m, a, b = load()
    if shift_a:
        a = a.copy()
        a.index = a.index + pd.Timedelta(hours=1)  # interval-beginning -> interval-ending
    if b_to_mw:
        b = b / 1000.0
    df = pd.concat({"m": m, "a": a, "b": b}, axis=1, sort=True)
    if fill_zero:
        df = df.fillna(0.0)
    if common:
        df = df.dropna()
        out: dict[str, dict[str, float] | int] = {"hours_used": len(df)}
        cap = capacity(df.index, cap_reference)
        out["a"] = metrics(df["a"], df["m"], cap)
        out["b"] = metrics(df["b"], df["m"], cap)
        return out
    out = {}
    for k in ("a", "b"):
        d = df[["m", k]].dropna()
        out[k] = metrics(d[k], d["m"], capacity(d.index, cap_reference))
        out[f"hours_used_{k}"] = len(d)
    return out


def flat(sol: dict) -> dict[str, float]:
    vals = {}
    for k in ("a", "b"):
        vals[f"{k}_mae_mw"] = sol[k]["mae_mw"]
        vals[f"{k}_rmse_mw"] = sol[k]["rmse_mw"]
        vals[f"{k}_nrmse_pct"] = sol[k]["nrmse_cap_pct"]
    if "hours_used" in sol:
        vals["hours_used"] = sol["hours_used"]
    return vals


def main() -> None:
    import argparse

    global MATERIALS, OUT, CHANGE
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--materials", type=Path, default=MATERIALS)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--capacity-change", default=str(CHANGE), help="effective date of the 120 MW capacity")
    args = ap.parse_args()
    MATERIALS, OUT, CHANGE = args.materials, args.out, pd.Timestamp(args.capacity_change)
    correct = solve()
    values = flat(correct)
    variants = {
        "model_b_not_converted_from_kw": flat(solve(b_to_mw=False)),
        "model_a_timestamps_not_aligned": flat(solve(shift_a=False)),
        "missing_values_filled_with_zero": flat(solve(fill_zero=True)),
        "no_common_sample": {**{k: v for k, v in flat(solve(common=False)).items()}},
    }
    const = {f"{k}_nrmse_pct": correct[k]["nrmse_const100_pct"] for k in ("a", "b")}
    meanv = {f"{k}_nrmse_pct": correct[k]["nrmse_mean_pct"] for k in ("a", "b")}
    variants["nrmse_with_constant_100mw_capacity"] = const
    variants["nrmse_normalised_by_mean_measured_power"] = meanv
    variants["capacity_looked_up_at_interval_end"] = {
        f"{k}_nrmse_pct": solve(cap_reference="end")[k]["nrmse_cap_pct"] for k in ("a", "b")
    }
    expected = {
        "task": "compare-forecast-models",
        "values": {k: {"value": round(v, 6) if isinstance(v, float) else v,
                       "rel_tol": 0.0 if k == "hours_used" else 0.001,
                       "abs_tol": 0 if k == "hours_used" else 0.0005} for k, v in values.items()},
        "variants": {name: {k: round(v, 6) if isinstance(v, float) else v for k, v in vals.items()}
                     for name, vals in variants.items()},
        "required_open_issues": [
            {"id": "model_b_lead_time_unknown",
             "description": "The issue time / lead time of model B is not documented.",
             "any_of": ["lead time", "issue time", "issued", "issuance", "horizon"]},
        ],
        "notes": "hours_used counts hours where the measurement and both forecasts are available after aligning model A.",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(expected, indent=2))
    print(json.dumps(expected, indent=2))


if __name__ == "__main__":
    main()
