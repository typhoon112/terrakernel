def tool_inputs_fingerprint(project: Project, tool: ToolPlan) -> str:
    """Fingerprint tool semantics and the compiler that renders implementations/tests."""
    kb = project.kb
    parts = [tool.model_dump_json(), hashlib.sha256(Path(__file__).read_bytes()).hexdigest()]
    if tool.strategy == "candidate" and "int" in _return_contract(tool):
        parts.append("returns:int")
    for oid in sorted(set(tool.method_ids + tool.test_object_ids + ([tool.capability_id] if tool.capability_id else []))):
        o = kb.object(oid)
        if o is not None:
            parts.append(json.dumps({"id": o.id, "name": o.name, "attributes": o.attributes, "basis": o.basis.value},
                                    sort_keys=True, default=str))
        for lk in kb.links(oid):
            ev = kb.evidence_by_ids([lk.evidence_id]).get(lk.evidence_id)
            parts.append(f"{lk.evidence_id}:{ev.content_hash if ev else '-'}")
    if tool.capability_id:
        cap = kb.object(tool.capability_id)
        src = project.materials_dir / str(cap.attributes.get("file", "")) if cap else None
        if src and src.is_file():
            parts.append(hashlib.sha256(src.read_bytes()).hexdigest())
    return hashlib.sha256("\n".join(parts).encode()).hexdigest()[:16]


def _previous_entry(repo: Path, name: str) -> dict[str, Any] | None:
    reg = repo / "tools" / "research_tools" / "registry.json"
    if not reg.exists():
        return None
    try:
        return next((t for t in json.loads(reg.read_text()).get("tools", []) if t.get("name") == name), None)
    except json.JSONDecodeError:
        return None


def compile_tool(repo: Path, project: Project, llm: LLMClient, tool: ToolPlan, model: str) -> dict[str, Any]:
    fp = tool_inputs_fingerprint(project, tool)
    prev = _previous_entry(repo, tool.name)
    module_file = repo / "tools" / "research_tools" / "tools" / f"{tool.name}.py"
    test_file = repo / "tests" / f"test_{tool.name}.py"
    if prev and prev.get("inputs_fingerprint") == fp and prev.get("status") in ("verified", "tested") \
            and module_file.exists() and test_file.exists():
        res = run_pytest(repo, f"tests/test_{tool.name}.py")
        ok = res["returncode"] == 0 and res["failed"] == 0 and res["errors"] == 0 and res["passed"] > 0
        if ok:
            return {**prev, "tests": {"passed": res["passed"], "failed": 0}, "reused": True}
    entry: dict[str, Any] = {
        "name": tool.name, "module": f"research_tools.tools.{tool.name}", "description": tool.purpose,
        "strategy": tool.strategy, "inputs": [i.model_dump() for i in tool.inputs],
        "output_description": tool.output_description, "output_unit": tool.output_unit,
        "objects": sorted(set(tool.method_ids + tool.test_object_ids + ([tool.capability_id] if tool.capability_id else []))),
        "test_file": f"tests/test_{tool.name}.py", "knowledge": f"knowledge/computations/{tool.name.replace('_', '-')}.md",
        "problems": [], "inputs_fingerprint": fp,
    }
    module_path = repo / "tools" / "research_tools" / "tools" / f"{tool.name}.py"
    cases, problems = derive_reference_tests(project, llm, tool, model)
    entry["problems"] += problems
    entry["reference_cases"] = len(cases)
    try:
        if tool.strategy == "wrap_existing":
            code, info = compile_wrapped(repo, project, tool)
            entry["reuse"] = info
            write_text_stable(module_path, code)
        else:
            impl = implement_candidate(project, llm, tool, model)
            write_text_stable(module_path, render_candidate_module(tool, impl, project))
    except Exception as e:
        entry.update(status="failed", problems=entry["problems"] + [str(e)])
        return entry
    test_path = repo / entry["test_file"]
    test_path.parent.mkdir(parents=True, exist_ok=True)
    write_text_stable(test_path, render_test_file(tool, cases, tool.properties))
    res = run_pytest(repo, entry["test_file"])
    if (res["failed"] or res["errors"] or res["returncode"] not in (0, 5)) and tool.strategy == "candidate":
        feedback = evaluate_cases(repo, tool, cases) or [res["output"][-1500:]]
        previous = module_path.read_text()
        try:
            impl = implement_candidate(project, llm, tool, model, feedback="\n".join(feedback), previous=previous)
            write_text_stable(module_path, render_candidate_module(tool, impl, project))
            res = run_pytest(repo, entry["test_file"])
            entry["repaired"] = True
        except Exception as e:
            entry["problems"].append(f"repair failed: {e}")
    entry["tests"] = {"passed": res["passed"], "failed": res["failed"] + res["errors"]}
    if res["returncode"] == 0 and res["failed"] == 0 and res["errors"] == 0 and res["passed"] > 0:
        entry["status"] = "verified" if cases else "tested"
    else:
        entry["status"] = "failed"
        entry["test_output"] = res["output"][-3000:]
    return entry


def runtime_test_file(plan: RepositoryPlan) -> str:
    """Generic checks that the runtime enforces the documented data semantics."""
    return textwrap.dedent('''\
        """Checks that the data runtime applies the documented semantics (generated by TerraKernel)."""

        import numpy as np
        import pandas as pd
        import pytest
        import yaml

        import research_tools as rt
        from research_tools._runtime import CONFIG_DIR, SOURCES_DIR
        from research_tools._units import conversion

        DATASETS = yaml.safe_load((CONFIG_DIR / "datasets.yaml").read_text())["datasets"]
        PARAMETERS = yaml.safe_load((CONFIG_DIR / "parameters.yaml").read_text())["parameters"]
        CONVENTIONS = yaml.safe_load((CONFIG_DIR / "conventions.yaml").read_text())
        CANONICAL = {u["quantity"]: u["unit"] for u in CONVENTIONS["canonical_units"]}


        @pytest.mark.parametrize("ds", DATASETS, ids=[d["name"] for d in DATASETS])
        def test_dataset_loads_in_canonical_form(ds):
            if ds.get("format") == "netcdf":
                for col in ds["value_columns"]:
                    da = rt.load_array(ds["name"], col["column"])
                    assert da.size > 0
                    if col.get("unit") is None:
                        assert da.attrs["terrakernel"]["unit"] == "unknown"
                return
            raw = rt.load_dataset(ds["name"], raw=True)
            if ds.get("time_convention") == "unknown" or any(c.get("unit") is None for c in ds["value_columns"]):
                pytest.skip("semantics not fully documented; see open_issues")
            df = rt.load_dataset(ds["name"])
            assert len(df) == len(raw)
            if ds.get("time_column"):
                assert str(df.index.tz) == "UTC"
                assert df.index.is_monotonic_increasing and df.index.is_unique
                raw = raw.assign(_t=pd.to_datetime(raw[ds["time_column"]], utc=True)).sort_values("_t")
                shift = pd.Timedelta(0)
                target = CONVENTIONS["canonical_time_convention"]
                if ds["time_convention"] != target and "instant" not in (ds["time_convention"], target):
                    step = pd.Timedelta(pd.tseries.frequencies.to_offset(ds["resolution"]))
                    shift = step if ds["time_convention"] == "interval_beginning" else -step
                assert (df.index == pd.DatetimeIndex(raw["_t"]) + shift).all()
            for col in ds["value_columns"]:
                target = CANONICAL.get(col["quantity"], col["unit"])
                scale, offset = conversion(col["unit"], target)
                expected = raw[col["column"]].astype(float).to_numpy() * scale + offset
                np.testing.assert_allclose(df[col["column"]].to_numpy(), expected, rtol=1e-12, equal_nan=True)


        @pytest.mark.parametrize("p", PARAMETERS, ids=[p["name"] for p in PARAMETERS])
        def test_parameter_schedule_boundaries(p):
            if p.get("lookup") == "unknown":
                pytest.skip("lookup rule not documented")
            hour = pd.Timedelta("1h")
            for i, entry in enumerate(p["schedule"]):
                start = pd.Timestamp(entry["valid_from"]).tz_convert("UTC")
                # timestamps labelled by the canonical convention; the documented lookup decides the value
                idx = pd.DatetimeIndex([start + hour, start + 2 * hour, start + 3 * hour])
                values = rt.parameter_series(p["name"], idx, resolution="1h")
                assert values.iloc[-1] == pytest.approx(entry["value"])
                if i > 0 and p["lookup"] == "interval_start" and CONVENTIONS["canonical_time_convention"] == "interval_ending":
                    boundary = rt.parameter_series(p["name"], pd.DatetimeIndex([start, start + hour]), resolution="1h")
                    assert boundary.iloc[0] == pytest.approx(p["schedule"][i - 1]["value"])
                    assert boundary.iloc[1] == pytest.approx(entry["value"])


        def test_common_valid_sample_imputes_nothing():
            idx = pd.date_range("2000-01-01", periods=4, freq="h", tz="UTC")
            a = pd.Series([1.0, None, 3.0, 4.0], index=idx)
            b = pd.Series([1.0, 2.0, None, 4.0], index=idx)
            out = rt.common_valid_sample(a=a, b=b)
            assert list(out.index) == [idx[0], idx[3]]
        ''')


def compile_tools(repo: Path, project: Project, llm: LLMClient, plan: RepositoryPlan, model: str) -> list[dict[str, Any]]:
    from concurrent.futures import ThreadPoolExecutor

    write_configs(repo, plan, project)
    write_runtime(repo)
    (repo / "tests").mkdir(exist_ok=True)
    write_text_stable(repo / "tests" / "test_runtime.py", runtime_test_file(plan))
    write_text_stable(repo / "tests" / "conftest.py", 
        '"""Make the research_tools package importable when running pytest from the repository root."""\n\n'
        "import sys\nfrom pathlib import Path\n\nsys.path.insert(0, str(Path(__file__).resolve().parents[1] / \"tools\"))\n")
    write_package_init(repo, [])
    buildable = [t for t in plan.tools if t.strategy != "knowledge_only"]
    planned = {t.name for t in buildable}
    for old in sorted((repo / "tests").glob("test_*.py")):
        name = old.stem.removeprefix("test_")
        if name != "runtime" and name not in planned:
            old.unlink()
            project.emit("compile", "item", f"removed stale tests/{old.name} (tool no longer planned)")
    tools_dir = repo / "tools" / "research_tools" / "tools"
    for old in sorted(tools_dir.glob("*.py")) if tools_dir.exists() else []:
        if old.stem != "__init__" and old.stem not in planned:
            old.unlink()
    comp_dir = repo / "knowledge" / "computations"
    for old in sorted(comp_dir.glob("*.md")) if comp_dir.exists() else []:
        if old.stem != "index" and old.stem.replace("-", "_") not in planned:
            old.unlink()
    with ThreadPoolExecutor(max_workers=max(1, llm.settings.max_concurrency)) as pool:
        entries = list(pool.map(lambda t: compile_tool(repo, project, llm, t, model), buildable))
    for e in entries:
        project.emit("compile", "item", f"tool {e['name']}: {e['status']} "
                     f"({e.get('tests', {}).get('passed', 0)} passed, {e.get('tests', {}).get('failed', 0)} failed, "
                     f"{e.get('reference_cases', 0)} reference cases)", tool=e["name"], status=e["status"])
        for p in e.get("problems", [])[:5]:
            project.emit("compile", "warning", f"tool {e['name']}: {p}")
    write_package_init(repo, entries)
    rt_res = run_pytest(repo, "tests/test_runtime.py")
    project.emit("compile", "item", f"runtime checks: {rt_res['passed']} passed, {rt_res['failed'] + rt_res['errors']} failed")
    if rt_res["failed"] or rt_res["errors"]:
        project.emit("compile", "warning", "runtime checks failed:\n" + rt_res["output"][-1500:])
    return entries, rt_res
