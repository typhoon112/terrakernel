# ============================================================== configs and runtime
def write_configs(repo: Path, plan: RepositoryPlan, project: Project) -> None:
    cfg_dir = repo / "tools" / "research_tools" / "config"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    header = "# Generated by TerraKernel from the documentation in sources/. Each entry lists the knowledge\n" \
             "# objects it was derived from; edit the documentation and run `terrakernel update` instead.\n"
    datasets = []
    for d in plan.datasets:
        datasets.append({
            "name": d.name, "file": d.file, "format": d.format, "sheet": d.sheet, "description": d.description,
            "time_column": d.time_column,
            "time_convention": d.time_convention, "timezone": d.timezone, "resolution": d.resolution,
            "missing_values": d.missing_values,
            "value_columns": [{"column": c.column, "quantity": c.quantity, "unit": c.unit,
                               "evidence": c.evidence_object_ids} for c in d.value_columns],
            "evidence": sorted(set(d.evidence_object_ids + [d.profile_object_id])),
            "open_issues": d.open_issues,
        })
    write_text_stable(cfg_dir / "datasets.yaml", header + yaml.safe_dump({"datasets": datasets}, sort_keys=False,
                                                                   allow_unicode=True, width=110))
    params = [{"name": p.name, "description": p.description, "quantity": p.quantity, "unit": p.unit,
               "lookup": p.lookup, "schedule": [{"valid_from": e.valid_from, "value": e.value} for e in p.schedule],
               "evidence": p.evidence_object_ids} for p in plan.parameters]
    write_text_stable(cfg_dir / "parameters.yaml", header + yaml.safe_dump({"parameters": params}, sort_keys=False,
                                                                     allow_unicode=True, width=110))
    conv = {"canonical_time_convention": plan.conventions.canonical_time_convention,
            "canonical_units": [{"quantity": u.quantity, "unit": u.unit} for u in plan.conventions.canonical_units],
            "evidence": plan.conventions.evidence_object_ids}
    write_text_stable(cfg_dir / "conventions.yaml", header + yaml.safe_dump(conv, sort_keys=False, allow_unicode=True,
                                                                      width=110))


def write_runtime(repo: Path) -> None:
    pkg = repo / "tools" / "research_tools"
    (pkg / "tools").mkdir(parents=True, exist_ok=True)
    (pkg / "_vendor").mkdir(parents=True, exist_ok=True)
    write_text_stable(pkg / "_runtime.py", (TEMPLATES / "runtime.py").read_text())
    write_text_stable(pkg / "_checks.py", (TEMPLATES / "checks.py").read_text())
    units = UNITS_SRC.read_text().replace('"""Unit registry shared by the planner (validation) and the generated runtime.',
                                          '"""Unit registry (generated by TerraKernel).')
    write_text_stable(pkg / "_units.py", units)
    write_text_stable(pkg / "tools" / "__init__.py", '"""Research tools compiled from the materials (see registry.json)."""\n')
    write_text_stable(pkg / "_vendor" / "__init__.py", '"""Unmodified code copied from sources/ for reuse by wrapped tools."""\n')
    write_text_stable(repo / "tools" / "mcp_server.py", (TEMPLATES / "mcp_server.py").read_text())


