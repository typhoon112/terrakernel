# ============================================================== pytest runner
def python_env(repo: Path) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith(("ANTHROPIC", "OPENAI", "AWS_", "GOOGLE_"))}
    env["PYTHONPATH"] = str(repo / "tools")
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def run_pytest(repo: Path, test_file: str, timeout: int = 300) -> dict[str, Any]:
    cmd = [sys.executable, "-m", "pytest", test_file, "-q", "-p", "no:cacheprovider", "--no-header", "-rN",
           "--tb=line", "-o", "addopts="]
    try:
        proc = subprocess.run(cmd, cwd=repo, env=python_env(repo), capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"passed": 0, "failed": 1, "errors": 0, "output": "timeout", "returncode": -1}
    out = proc.stdout + proc.stderr
    m_pass = re.search(r"(\d+) passed", out)
    m_fail = re.search(r"(\d+) failed", out)
    m_err = re.search(r"(\d+) errors?", out)
    return {"passed": int(m_pass.group(1)) if m_pass else 0, "failed": int(m_fail.group(1)) if m_fail else 0,
            "errors": int(m_err.group(1)) if m_err else 0, "output": out[-6000:], "returncode": proc.returncode}


# ============================================================== reference tests
class CaseInput(BaseModel):
    name: str = Field(description="tool input name")
    values: list[float] = Field(description="the series values in source order, or one value for a number input")


class TestCase(BaseModel):
    id: str = Field(description="short kebab-case id")
    inputs: list[CaseInput]
    expected: float
    expected_quote: str
    expected_evidence_id: str
    input_evidence_ids: list[str]
    notes: str = ""


class TestDerivation(BaseModel):
    cases: list[TestCase]
    skipped: list[str] = Field(default_factory=list)


def _numbers(text: str) -> list[float]:
    out = []
    for m in NUMBER_RE.findall(text.replace("−", "-")):
        try:
            out.append(float(m.replace(",", "") if m.count(",") and "." in m else m.replace(",", ".")))
        except ValueError:
            pass
    return out


def _quoted_precision(expected: float, quote: str) -> float | None:
    for m in NUMBER_RE.findall(quote.replace("−", "-")):
        lit = m.replace(",", ".")
        try:
            if abs(float(lit) - expected) <= 1e-12 + 1e-9 * abs(expected):
                decimals = len(lit.split(".")[1]) if "." in lit else 0
                return 0.5 * 10 ** (-decimals) + 1e-9
        except ValueError:
            continue
    return None


def derive_reference_tests(project: Project, llm: LLMClient, tool: ToolPlan, model: str) -> tuple[list[dict], list[str]]:
    kb = project.kb
    if tool.output_kind == "series":
        return [], ["per-row (series) output: only shape and missing-value behaviour can be tested"]
    if not tool.test_object_ids:
        return [], ["no reference objects planned"]
    ev_ids: list[str] = []
    for oid in tool.test_object_ids + tool.method_ids:
        ev_ids += [lk.evidence_id for lk in kb.links(oid)]
    evidence = kb.evidence_by_ids(ev_ids)
    # include neighbouring units on the same page/section (tables are often next to the stated result)
    for ev in list(evidence.values()):
        for other in kb.evidence(ev.source_id):
            if ev.locator.page is not None and other.locator.page == ev.locator.page and \
                    other.locator.section == ev.locator.section:
                evidence.setdefault(other.id, other)
    if not evidence:
        return [], ["no evidence for the reference objects"]
    sig = ", ".join(f"{i.name}: {i.kind}{' [' + i.unit + ']' if i.unit else ''}" for i in tool.inputs)
    prompt = (f"Tool: {tool.name}({sig}) -> {tool.output_description} [{tool.output_unit or 'unitless'}]\n"
              f"Purpose: {tool.purpose}\n\nEvidence units:\n" + "\n\n".join(
                  f'<evidence id="{e.id}" locator="{e.locator.short()}">\n{e.content}\n</evidence>'
                  for e in sorted(evidence.values(), key=lambda x: (x.source_id, x.order))))
    try:
        result = llm.structured(prompt, TestDerivation, system=skill_body("derive-tests"), model=model,
                                max_tokens=8000, tool_name="submit_tests",
                                tool_description="Submit reference test cases derived from the evidence.")
    except Exception as e:
        return [], [f"test derivation failed: {e}"]
    accepted, problems = [], list(result.skipped)
    input_names = {i.name: i for i in tool.inputs}
    for case in result.cases:
        why = []
        given = {ci.name: ci.values for ci in case.inputs}
        case_inputs: dict[str, list[float] | float] = {}
        for name, vals in given.items():
            spec = input_names.get(name)
            case_inputs[name] = vals[0] if spec is not None and spec.kind == "number" and len(vals) == 1 else vals
        ev = evidence.get(case.expected_evidence_id)
        if ev is None:
            why.append(f"unknown evidence {case.expected_evidence_id}")
        elif quote_score(case.expected_quote, ev.content) < 88:
            why.append("expected_quote not found in the evidence")
        tol = _quoted_precision(case.expected, case.expected_quote)
        if tol is None:
            why.append(f"expected value {case.expected} is not written in the quote")
        if set(case_inputs) != set(input_names):
            why.append(f"inputs {sorted(case_inputs)} do not match tool inputs {sorted(input_names)}")
        pool: set[float] = set()
        for eid in case.input_evidence_ids:
            if eid in evidence:
                pool |= {round(x, 9) for x in _numbers(evidence[eid].content)}
        for name, value in case_inputs.items():
            vals = value if isinstance(value, list) else [value]
            spec = input_names.get(name)
            if spec and spec.kind == "series" and not isinstance(value, list):
                why.append(f"input {name} must be a list")
            missing = [v for v in vals if round(float(v), 9) not in pool]
            if missing and "convert" not in case.notes.lower():
                why.append(f"input {name} values {missing[:5]} do not appear in the cited evidence")
        if why:
            problems.append(f"case {case.id} rejected: " + "; ".join(why))
            continue
        accepted.append({"id": re.sub(r"[^a-z0-9\-]+", "-", case.id.lower()).strip("-") or f"case-{len(accepted)+1}",
                         "inputs": case_inputs, "expected": case.expected, "abs_tol": tol,
                         "source": case.expected_evidence_id, "quote": case.expected_quote,
                         "input_sources": case.input_evidence_ids, "notes": case.notes})
    return accepted, problems


def render_test_file(tool: ToolPlan, cases: list[dict], properties: list[str]) -> str:
    if tool.output_kind == "series":
        properties = []  # numeric invariants do not apply to per-row outputs
        cases = []
    series_inputs = [i.name for i in tool.inputs if i.kind == "series"]
    lines = [
        f'"""Tests for `{tool.name}` (generated by TerraKernel).',
        "",
        "REFERENCE_CASES take inputs and expected values from the materials; each case cites the",
        "evidence unit that states the expected value. Property tests check generic invariants.",
        '"""',
        "",
        "import numpy as np",
        "import pytest",
        "",
        f"from research_tools.tools.{tool.name} import {tool.name}",
        "",
        f"REFERENCE_CASES = {json.dumps(cases, indent=4, ensure_ascii=False)}",
        "",
        "",
        "def _prepare(inputs):",
        "    return {k: (np.asarray(v, dtype=float) if isinstance(v, list) else v) for k, v in inputs.items()}",
        "",
        "",
    ]
    if cases:
        lines += [
            '@pytest.mark.parametrize("case", REFERENCE_CASES, ids=[c["id"] for c in REFERENCE_CASES])',
            "def test_reference(case):",
            f"    result = {tool.name}(**_prepare(case['inputs']))",
            "    assert isinstance(result, (int, float)), f'expected a number, got {type(result).__name__}'",
            "    assert result == pytest.approx(case['expected'], abs=case['abs_tol']), (",
            "        f\"result {result} differs from the value stated in {case['source']}: {case['quote']!r}\")",
            "",
            "",
        ]
    gen = ["def _random_inputs(seed=0, n=48):", "    rng = np.random.default_rng(seed)", "    return {"]
    for i in tool.inputs:
        if i.kind == "series":
            gen.append(f"        {i.name!r}: rng.uniform(1.0, 100.0, n),")
        elif i.kind == "number":
            gen.append(f"        {i.name!r}: float(rng.integers(1, 5)),")
        else:
            gen.append(f"        {i.name!r}: 'x',")
    gen += ["    }", "", ""]
    if properties or (series_inputs and (tool.output_kind == "series" or tool.missing_values == "reject")):
        lines += gen
    a, b = (series_inputs + [None, None])[:2]
    for prop in properties:
        if prop == "zero_when_equal" and a and b:
            lines += ["def test_zero_when_equal():", "    x = _random_inputs()", f"    x[{b!r}] = x[{a!r}].copy()",
                      f"    assert {tool.name}(**x) == pytest.approx(0.0, abs=1e-9)", "", ""]
        elif prop == "non_negative":
            lines += ["def test_non_negative():", "    for seed in range(5):",
                      f"        assert {tool.name}(**_random_inputs(seed)) >= 0", "", ""]
        elif prop == "symmetric" and a and b:
            lines += ["def test_symmetric():", "    x = _random_inputs(1)", f"    y = dict(x, {a}=x[{b!r}], {b}=x[{a!r}])",
                      f"    assert {tool.name}(**x) == pytest.approx({tool.name}(**y), rel=1e-9)", "", ""]
        elif prop == "scale_invariant":
            lines += ["def test_scale_invariant():", "    x = _random_inputs(2)",
                      "    y = {k: (v * 7.3 if not isinstance(v, str) else v) for k, v in x.items()}",
                      f"    assert {tool.name}(**x) == pytest.approx({tool.name}(**y), rel=1e-9)", "", ""]
    if tool.output_kind == "series" and a:
        lines += ["def test_returns_one_value_per_row():", "    x = _random_inputs(4, n=30)",
                  f"    out = {tool.name}(**x)", "    import pandas as pd",
                  "    assert isinstance(out, pd.Series)", f"    assert len(out) == len(x[{a!r}])", "", ""]
    if a and tool.missing_values == "reject":
        lines += ["def test_rejects_missing_values():", "    x = _random_inputs(3)",
                  f"    x[{a!r}] = x[{a!r}].copy()", f"    x[{a!r}][0] = np.nan", "    with pytest.raises(ValueError):",
                  f"        {tool.name}(**x)", ""]
    return "\n".join(lines).rstrip() + "\n"


# ============================================================== wrapped tools
def _vendor_safe(code: str) -> tuple[bool, str]:
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return False, f"syntax error: {e}"
    for node in tree.body:
        if isinstance(node, ast.Import | ast.ImportFrom | ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef |
                      ast.Assign | ast.AnnAssign):
            continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
            continue
        if isinstance(node, ast.If) and "__name__" in ast.unparse(node.test):
            continue
        return False, f"top-level statement at line {node.lineno} would run on import"
    return True, ""


def _func_params(code: str, symbol: str) -> list[str] | None:
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.FunctionDef) and node.name == symbol:
            return [a.arg for a in node.args.args]
    return None


def compile_wrapped(repo: Path, project: Project, tool: ToolPlan) -> tuple[str, dict[str, Any]]:
    cap = project.kb.object(tool.capability_id or "")
    if cap is None:
        raise ValueError(f"capability {tool.capability_id} not found")
    src_rel = str(cap.attributes.get("file") or "")
    symbol = str(cap.attributes.get("symbol"))
    src_path = project.materials_dir / src_rel
    code = src_path.read_text(encoding="utf-8")
    ok, why = _vendor_safe(code)
    if not ok:
        raise ValueError(f"cannot reuse {src_rel} safely: {why}")
    module = re.sub(r"[^a-zA-Z0-9_]", "_", Path(src_rel).stem).lower()
    vendor = repo / "tools" / "research_tools" / "_vendor" / f"{module}.py"
    write_text_stable(vendor, code)
    sha = hashlib.sha256(code.encode()).hexdigest()
    params = _func_params(code, symbol)
    if params is None:
        raise ValueError(f"function {symbol} not found in {src_rel}")
    names = [i.name for i in tool.inputs]
    call_args = []
    for pos, p in enumerate(params):
        if p in names:
            call_args.append(f"{p}=_v[{p!r}]" if tool.inputs[names.index(p)].kind == "series" else f"{p}={p}")
        elif pos < len(names):
            n = names[pos]
            call_args.append(f"_v[{n!r}]" if tool.inputs[pos].kind == "series" else n)
    series = [i.name for i in tool.inputs if i.kind == "series"]
    numbers = [i.name for i in tool.inputs if i.kind == "number"]
    lines = [cap.attributes.get("lines") or ["?", "?"]][0]
    doc_inputs = "\n".join(f"        {i.name} ({i.kind}{', ' + i.unit if i.unit else ''}): {i.description}" for i in tool.inputs)
    body = [
        f'"""{tool.purpose}', "",
        f"Strategy: wrap_existing. Calls `{symbol}` from sources/{src_rel} (lines {lines[0]}-{lines[1]}) unchanged;",
        "this wrapper only adds input checks.",
        f"Source SHA-256: {sha}",
        '"""', "", "from __future__ import annotations", "", "from research_tools import _checks",
        f"from research_tools._vendor import {module} as _source", "", "",
        f"def {tool.name}({', '.join(names)}) -> float:",
        f'    """{tool.purpose}', "", "    Inputs:", doc_inputs,
        f"    Returns: {tool.output_description}" + (f" [{tool.output_unit}]" if tool.output_unit else ""),
        '    """',
    ]
    if series:
        body.append(f"    _v = _checks.aligned_arrays({', '.join(f'{s}={s}' for s in series)})")
    for n in numbers:
        body.append(f"    {n} = _checks.as_number({n!r}, {n})")
    body.append(f"    return float(_source.{symbol}({', '.join(call_args)}))")
    return "\n".join(body) + "\n", {"vendor": f"tools/research_tools/_vendor/{module}.py", "source": src_rel,
                                    "symbol": symbol, "sha256": sha}


# ============================================================== candidate tools
class Implementation(BaseModel):
    code: str = Field(description="Python source of one function starting with def")
    notes: str = ""


def check_candidate_code(code: str, tool: ToolPlan) -> list[str]:
    problems = []
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return [f"syntax error: {e}"]
    funcs = [n for n in tree.body if isinstance(n, ast.FunctionDef)]
    others = [n for n in tree.body if not isinstance(n, ast.FunctionDef | ast.Import | ast.ImportFrom)]
    if len(funcs) != 1 or funcs[0].name != tool.name:
        problems.append(f"the code must define exactly one top-level function named {tool.name}")
    if others:
        problems.append("only one function (and optional imports) may be defined at top level")
    if funcs:
        params = [a.arg for a in funcs[0].args.args]
        if params != [i.name for i in tool.inputs]:
            problems.append(f"parameters must be exactly {[i.name for i in tool.inputs]}, got {params}")
    for node in ast.walk(tree):
        if isinstance(node, ast.Import | ast.ImportFrom):
            mods = [a.name for a in node.names] if isinstance(node, ast.Import) else [node.module or ""]
            for m in mods:
                if m.split(".")[0] not in ALLOWED_IMPORTS:
                    problems.append(f"import of {m!r} is not allowed")
        if isinstance(node, ast.Name) and node.id in FORBIDDEN_NAMES:
            problems.append(f"use of {node.id!r} is not allowed")
        if isinstance(node, ast.Attribute) and node.attr in ("system", "popen", "remove", "unlink", "rmtree"):
            problems.append(f"use of .{node.attr} is not allowed")
    return problems


def _method_context(project: Project, tool: ToolPlan) -> str:
    kb = project.kb
    parts = []
    for mid in tool.method_ids:
        o = kb.object(mid)
        if o is None:
            continue
        parts.append(json.dumps({"id": o.id, "type": o.type.value, "name": o.name, "summary": o.summary,
                                 "attributes": o.attributes}, ensure_ascii=False, default=str))
        for lk in kb.links(mid):
            ev = kb.evidence_by_ids([lk.evidence_id]).get(lk.evidence_id)
            if ev and ev.kind != "table":
                parts.append(f"Evidence {ev.id} ({ev.locator.short()}): {ev.content[:1200]}")
    for rel in kb.relations():
        if rel.src in tool.method_ids or rel.dst in tool.method_ids:
            if rel.type.value in ("conflicts_with", "applies_to", "depends_on", "variant_of"):
                parts.append(f"Relation {rel.type.value}: {rel.src} -> {rel.dst}: {rel.note}")
    return "\n".join(parts)


_INTEGER_OUTPUT = re.compile(r"\b(integer|count|number of|index|position)\b", re.I)


def _return_contract(tool: ToolPlan) -> str:
    if tool.output_kind == "series":
        return "return a pandas.Series"
    if _INTEGER_OUTPUT.search(f"{tool.output_description} {tool.output_unit or ''}"):
        # counts and positions are used for indexing and comparisons: a float 0.0 breaks `array[i]`
        return "return one Python int"
    return "return one float"


def implement_candidate(project: Project, llm: LLMClient, tool: ToolPlan, model: str,
                        feedback: str | None = None, previous: str | None = None) -> str:
    sig = ", ".join(i.name for i in tool.inputs)
    inputs = "\n".join(f"- {i.name} ({i.kind}{', unit ' + i.unit if i.unit else ''}): {i.description}" for i in tool.inputs)
    returns = _return_contract(tool)
    if tool.missing_values == "defined_by_method":
        missing = "the documented method defines how they count; implement that rule instead of rejecting NaN inputs."
    else:
        missing = "reject NaN inputs with _checks (the caller selects a common valid sample first)."
    prompt = "\n".join([
        f"Implement `def {tool.name}({sig})`.",
        f"Purpose: {tool.purpose}",
        f"Inputs:\n{inputs}",
        f"Output kind: {tool.output_kind} ({returns})",
        f"Missing values: {missing}",
        f"Output: {tool.output_description} ({tool.output_unit or 'unitless'})",
        f"Notes: {tool.notes}",
        "",
        "Available helpers (already imported): `_checks.aligned_arrays(**series) -> dict[str, np.ndarray]`, "
        "`_checks.as_number(name, value) -> float`, `_checks.ToolInputError`; numpy as np; pandas as pd; math.",
        "",
        f"Method knowledge:\n{_method_context(project, tool)}",
    ])
    if feedback and previous:
        prompt += f"\n\nYour previous implementation:\n```python\n{previous}\n```\nCheck results:\n{feedback}\n" \
                  "Re-read the documented definition carefully and return a corrected function."
    problems: list[str] = []
    for _ in range(2):
        impl = llm.structured(prompt + (("\n\nFix these problems: " + "; ".join(problems)) if problems else ""),
                              Implementation, system=skill_body("implement-tool"), model=model, max_tokens=8000,
                              tool_name="submit_implementation", tool_description="Submit the function source code.")
        code = impl.code.strip()
        if code.startswith("```"):
            code = re.sub(r"^```\w*\n|\n```$", "", code)
        problems = check_candidate_code(code, tool)
        if not problems:
            return code
    raise ValueError("candidate implementation rejected: " + "; ".join(problems))


def render_candidate_module(tool: ToolPlan, code: str, project: Project) -> str:
    kb = project.kb
    names = [kb.object(m).name for m in tool.method_ids if kb.object(m)]
    header = [f'"""{tool.purpose}', "",
              f"Strategy: candidate. Implemented by TerraKernel from the documented definition of: {', '.join(names)}.",
              f"Validation status and source references: see registry.json and tests/test_{tool.name}.py.",
              '"""', "", "from __future__ import annotations", "", "import math  # noqa: F401", "",
              "import numpy as np  # noqa: F401", "import pandas as pd  # noqa: F401", "",
              "from research_tools import _checks  # noqa: F401", "", ""]
    return "\n".join(header) + code.strip() + "\n"


def evaluate_cases(repo: Path, tool: ToolPlan, cases: list[dict]) -> list[str]:
    """Run reference inputs through a tool and report its results without the expected values."""
    script = textwrap.dedent(f"""
        import json, sys
        import numpy as np
        from research_tools.tools.{tool.name} import {tool.name}
        cases = json.loads(sys.stdin.read())
        out = []
        for c in cases:
            try:
                x = {{k: (np.asarray(v, dtype=float) if isinstance(v, list) else v) for k, v in c['inputs'].items()}}
                out.append({{'id': c['id'], 'result': float({tool.name}(**x))}})
            except Exception as e:
                out.append({{'id': c['id'], 'error': f'{{type(e).__name__}}: {{e}}'}})
        print(json.dumps(out))
        """)
    proc = subprocess.run([sys.executable, "-c", script], cwd=repo, env=python_env(repo), input=json.dumps(cases),
                          capture_output=True, text=True, timeout=120)
    try:
        results = json.loads(proc.stdout.strip().splitlines()[-1])
    except (IndexError, json.JSONDecodeError):
        return [f"could not run the function: {proc.stderr[-1500:]}"]
    lines = []
    for r, c in zip(results, cases, strict=False):
        if "error" in r:
            lines.append(f"case {r['id']}: raised {r['error']}")
        elif abs(r["result"] - c["expected"]) > c["abs_tol"]:
            lines.append(f"case {r['id']}: your function returned {r['result']:.6g}, which does not match the value "
                         f"stated in the materials (inputs: {json.dumps(c['inputs'])})")
    return lines


