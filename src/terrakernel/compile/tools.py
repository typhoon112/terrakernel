"""Compile tools: configuration, runtime, wrapped and candidate tools, and their tests.

Verification policy
- Reference tests take inputs and expected values from the materials. Each case must
  quote the evidence that states the expected value, and every input number must occur
  in the cited evidence. Tolerances follow the precision of the quoted number.
- Property tests check generic invariants chosen by the planner.
- A candidate implementation never sees the reference values. If it fails, it gets one
  repair attempt that shows its own results, not the expected ones.
- Status: ``verified`` (all tests pass, at least one reference case), ``tested`` (only
  property tests available, all pass) or ``failed``.
"""

